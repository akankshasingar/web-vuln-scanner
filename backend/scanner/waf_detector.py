"""
WAF Detector — VulnScan Pro
Detects the presence and identity of a Web Application Firewall (WAF) by
sending known probe requests and inspecting response headers, cookies, and
body content against a curated signature database.

Why run this first?
  A WAF will block/alter injection payloads, causing downstream modules
  (XSS, SQLi) to produce false negatives.  By fingerprinting the WAF we
  can warn the user rather than silently miss vulnerabilities.
"""

import requests
import re
import urllib3
from urllib.parse import urlparse

urllib3.disable_warnings()

