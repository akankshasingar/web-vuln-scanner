# ── Probe payloads that trigger most WAFs ──────────────────────────────────
PROBE_PATHS = [
    "/?id=1' OR '1'='1",          # SQLi probe
    "/?q=<script>alert(1)</script>",  # XSS probe
    "/?file=../../etc/passwd",     # Path traversal probe
]

# ── Detection thresholds ───────────────────────────────────────────────────
MIN_SIGNALS_FOR_DETECTION = 1   # Any single signal is enough (headers are strong)


def _check_response(response: requests.Response) -> list[str]:
    """
    Compare a single HTTP response against all WAF signatures.
    Returns a list of matched WAF names (may have >1 if overlapping sigs).
    """
    detected = []
    headers_lower = {k.lower(): v for k, v in response.headers.items()}
    cookies_str   = " ".join(response.cookies.keys()).lower()
    body_lower    = response.text[:8000].lower()   # only inspect first 8 KB

    for waf_name, sigs in WAF_SIGNATURES.items():
        signals = 0

        # Header checks
        for header_name, pattern in sigs.get("headers", {}).items():
            if header_name in headers_lower:
                if re.search(pattern, headers_lower[header_name], re.IGNORECASE):
                    signals += 1

        # Cookie checks
        for cookie_fragment in sigs.get("cookies", []):
            if re.search(cookie_fragment.lower(), cookies_str):
                signals += 1

        # Body checks
        for body_pattern in sigs.get("body", []):
            if re.search(body_pattern, body_lower, re.IGNORECASE):
                signals += 1

        if signals >= MIN_SIGNALS_FOR_DETECTION:
            detected.append(waf_name)

    return detected


def run_waf_detection(url: str, timeout: int = 8) -> dict:
    """
    Main entry point.  Tests the target URL with a baseline request and up to
    three probe payloads, returning a consolidated WAF detection result.

    Returns:
      {
        "waf_detected":  bool,
        "waf_name":      str | None,   # e.g. "Cloudflare"
        "confidence":    str,          # "High" / "Medium" / "Low" / "None"
        "evidence":      list[str],    # human-readable signals
        "blocked_probes": int,         # how many probes returned 4xx/5xx
        "error":         str | None,
      }
    """
    result = {
        "waf_detected":  False,
        "waf_name":      None,
        "confidence":    "None",
        "evidence":      [],
        "blocked_probes": 0,
        "error":         None,
    }

    # Normalise URL to just the origin
    try:
        parsed = urlparse(url if "://" in url else "http://" + url)
        origin = f"{parsed.scheme}://{parsed.netloc}"
    except Exception as e:
        result["error"] = f"Invalid URL: {e}"
        return result

    session = requests.Session()
    session.headers.update({"User-Agent": "Mozilla/5.0 (VulnScanPro/1.0)"})

    all_detected: list[str] = []
    blocked_count = 0

    # ── 1. Baseline (non-malicious) request ────────────────────────────────
    try:
        baseline = session.get(origin, timeout=timeout, verify=False)
        baseline_waf = _check_response(baseline)
        if baseline_waf:
            all_detected.extend(baseline_waf)
            result["evidence"].append(
                f"WAF signature in baseline response headers/cookies: {', '.join(baseline_waf)}"
            )
    except requests.exceptions.RequestException as e:
        result["error"] = f"Baseline request failed: {e}"
        return result

    # ── 2. Probe requests (attack-like payloads) ───────────────────────────
    for probe_path in PROBE_PATHS:
        probe_url = origin + probe_path
        try:
            probe_res = session.get(probe_url, timeout=timeout, verify=False,
                                    allow_redirects=True)
            probe_waf = _check_response(probe_res)
            all_detected.extend(probe_waf)

            if probe_res.status_code in [400, 403, 406, 429, 503]:
                blocked_count += 1
                result["evidence"].append(
                    f"Probe '{probe_path}' blocked with HTTP {probe_res.status_code}"
                )
        except requests.exceptions.RequestException:
            # A hard block (connection reset / close) is itself a WAF signal
            blocked_count += 1
            result["evidence"].append(
                f"Probe '{probe_path}' caused connection reset (hard block)"
            )

    # ── 3. Consolidate ─────────────────────────────────────────────────────
    result["blocked_probes"] = blocked_count

    # Pick the most-voted WAF name
    if all_detected:
        from collections import Counter
        top_name, _ = Counter(all_detected).most_common(1)[0]
        result["waf_detected"] = True
        result["waf_name"] = top_name

        unique_names = list(dict.fromkeys(all_detected))  # preserve order
        if len(unique_names) > 1:
            result["evidence"].insert(0,
                f"Multiple WAF signatures matched: {', '.join(unique_names)}"
            )
        else:
            result["evidence"].insert(0, f"WAF signature matched: {top_name}")

    elif blocked_count >= 2:
        # No named WAF but aggressive blocking → generic WAF-like behaviour
        result["waf_detected"] = True
        result["waf_name"] = "Unknown WAF"
        result["evidence"].insert(0,
            f"{blocked_count}/3 probe requests were blocked — WAF-like behaviour detected"
        )

    # ── 4. Confidence ──────────────────────────────────────────────────────
    if result["waf_detected"]:
        total_signals = len(all_detected) + blocked_count
        if total_signals >= 4 or (result["waf_name"] and result["waf_name"] != "Unknown WAF" and blocked_count >= 1):
            result["confidence"] = "High"
        elif total_signals >= 2:
            result["confidence"] = "Medium"
        else:
            result["confidence"] = "Low"
    else:
        result["confidence"] = "None"

    return result
